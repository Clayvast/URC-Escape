-- URC Escape Pager redemption fix. Run after pager-system-v2.sql.
create or replace function public.redeem_pager_code_for_puzzle(p_puzzle_id uuid,p_code text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_puzzle public.puzzles%rowtype; v_code public.pager_codes%rowtype;
begin
 if auth.uid() is null then raise exception 'You must be signed in to redeem a Pager code.'; end if;
 select * into v_puzzle from public.puzzles where id=p_puzzle_id and active=true and answer_type='pager';
 if not found then return jsonb_build_object('correct',false,'message','This Pager challenge is no longer active.'); end if;
 if not exists(select 1 from public.player_rooms where player_id=auth.uid() and room_name=v_puzzle.room_name) then
  return jsonb_build_object('correct',false,'message','Discover this room before attempting its puzzle.');
 end if;
 if exists(select 1 from public.puzzle_solves where player_id=auth.uid() and puzzle_id=p_puzzle_id) then
  return jsonb_build_object('correct',true,'already_solved',true,'message','You have already solved this puzzle.');
 end if;
 select * into v_code from public.pager_codes
 where puzzle_id=p_puzzle_id and code=trim(coalesce(p_code,'')) and expires_at>now()
  and consumed_at is null and generated_by<>auth.uid()
 order by created_at desc limit 1 for update;
 if not found then
  return jsonb_build_object('correct',false,'message','That code does not match this challenge, has expired, has already been used, or was generated by your own Pager. Ask the other player to generate a fresh code for this exact puzzle.');
 end if;
 update public.pager_codes set consumed_at=now() where id=v_code.id;
 insert into public.puzzle_solves(player_id,puzzle_id) values(auth.uid(),p_puzzle_id) on conflict do nothing;
 update public.player_progress set xp=xp+v_puzzle.reward_xp,key_shards=key_shards+v_puzzle.reward_shards,updated_at=now()
 where player_id=auth.uid();
 return jsonb_build_object('correct',true,'already_solved',false,'xp_awarded',v_puzzle.reward_xp,'shards_awarded',v_puzzle.reward_shards,'message','Pager code accepted. Challenge completed.');
end; $$;
revoke all on function public.redeem_pager_code_for_puzzle(uuid,text) from public,anon;
grant execute on function public.redeem_pager_code_for_puzzle(uuid,text) to authenticated;
notify pgrst,'reload schema';
