-- Pager redemption diagnostic. Run in Supabase SQL Editor after the two Pager setup migrations.
-- This preserves all security checks but returns the precise reason a code is rejected.

create or replace function public.redeem_pager_code_for_puzzle(p_puzzle_id uuid, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_puzzle public.puzzles%rowtype;
  v_code public.pager_codes%rowtype;
  v_entered_code text := left(regexp_replace(coalesce(p_code, ''), '[^0-9]', '', 'g'), 6);
begin
  if auth.uid() is null then
    raise exception 'You must be signed in to redeem a Pager code.';
  end if;

  if v_entered_code !~ '^[0-9]{6}$' then
    return jsonb_build_object('correct', false, 'message', 'Enter a valid six-digit Pager code.');
  end if;

  select * into v_puzzle
  from public.puzzles
  where id = p_puzzle_id and active = true and answer_type = 'pager';

  if not found then
    return jsonb_build_object('correct', false, 'message', 'The puzzle opened by the website is not an active Pager challenge. Please refresh the page and reopen it.');
  end if;

  if not exists (
    select 1 from public.player_rooms
    where player_id = auth.uid() and room_name = v_puzzle.room_name
  ) then
    return jsonb_build_object('correct', false, 'message', 'Discover this room before attempting its puzzle.');
  end if;

  if exists (
    select 1 from public.puzzle_solves
    where player_id = auth.uid() and puzzle_id = p_puzzle_id
  ) then
    return jsonb_build_object('correct', true, 'already_solved', true, 'message', 'You have already solved this puzzle.');
  end if;

  -- Lock the row for this exact challenge/code before checking its state.
  select * into v_code
  from public.pager_codes
  where puzzle_id = p_puzzle_id and code = v_entered_code
  order by created_at desc
  limit 1
  for update;

  if not found then
    if exists (select 1 from public.pager_codes where code = v_entered_code) then
      return jsonb_build_object('correct', false, 'message', 'This code exists, but it was generated for a different Pager challenge. Generate a new code for this exact puzzle.');
    end if;
    return jsonb_build_object('correct', false, 'message', 'No Pager code with those digits was found. Check the six digits or ask the other player to generate a fresh code.');
  end if;

  if v_code.expires_at <= now() then
    return jsonb_build_object('correct', false, 'message', 'This Pager code has expired. Generate a fresh code; codes last two minutes.');
  end if;

  if v_code.consumed_at is not null then
    return jsonb_build_object('correct', false, 'message', 'This Pager code has already been used. Ask the other player to generate a fresh code.');
  end if;

  if v_code.generated_by = auth.uid() then
    return jsonb_build_object('correct', false, 'message', 'You cannot redeem a code generated by your own account. The other player must generate it.');
  end if;

  update public.pager_codes
  set consumed_at = now()
  where id = v_code.id;

  insert into public.puzzle_solves(player_id, puzzle_id)
  values (auth.uid(), p_puzzle_id)
  on conflict do nothing;

  update public.player_progress
  set xp = xp + v_puzzle.reward_xp,
      key_shards = key_shards + v_puzzle.reward_shards,
      updated_at = now()
  where player_id = auth.uid();

  return jsonb_build_object(
    'correct', true,
    'already_solved', false,
    'xp_awarded', v_puzzle.reward_xp,
    'shards_awarded', v_puzzle.reward_shards,
    'message', 'Pager code accepted. Challenge completed.'
  );
end;
$$;

revoke all on function public.redeem_pager_code_for_puzzle(uuid, text) from public, anon;
grant execute on function public.redeem_pager_code_for_puzzle(uuid, text) to authenticated;
notify pgrst, 'reload schema';
