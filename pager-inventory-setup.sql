-- Pager inventory interaction: generate and redeem codes without opening a puzzle.
-- Run this in Supabase SQL Editor AFTER advanced-puzzle-setup.sql.

create table if not exists public.pager_codes (
  id uuid primary key default gen_random_uuid(),
  puzzle_id uuid not null references public.puzzles(id) on delete cascade,
  generated_by uuid not null references public.profiles(id) on delete cascade,
  code text not null,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists pager_codes_lookup_idx on public.pager_codes(code,expires_at);

create or replace function public.create_pager_code()
returns jsonb
language plpgsql security definer set search_path=public
as $$
declare
  v_puzzle public.puzzles%rowtype;
  v_code text;
  v_expires timestamptz;
begin
  if auth.uid() is null then raise exception 'Sign in first.'; end if;
  if not exists(select 1 from public.player_inventory where player_id=auth.uid() and item_id='pager' and quantity>0) then
    raise exception 'You need the Pager inventory item to generate a code.';
  end if;

  -- A generated code is associated with the first active Pager challenge.
  -- The player can now generate it from their inventory, wherever they are.
  select * into v_puzzle from public.puzzles
  where active=true and answer_type='pager'
  order by created_at,id limit 1;
  if not found then raise exception 'There is no active Pager challenge configured yet.'; end if;

  v_code:=lpad(floor(random()*1000000)::int::text,6,'0');
  v_expires:=now()+interval '2 minutes';
  insert into public.pager_codes(puzzle_id,generated_by,code,expires_at)
  values(v_puzzle.id,auth.uid(),v_code,v_expires);
  return jsonb_build_object('code',v_code,'expires_at',v_expires);
end;
$$;

create or replace function public.redeem_pager_code(p_code text)
returns jsonb
language plpgsql security definer set search_path=public
as $$
declare
  v_code public.pager_codes%rowtype;
  v_puzzle public.puzzles%rowtype;
begin
  if auth.uid() is null then raise exception 'Sign in first.'; end if;
  if not exists(select 1 from public.player_inventory where player_id=auth.uid() and item_id='pager' and quantity>0) then
    raise exception 'You need the Pager inventory item to enter a code.';
  end if;

  select * into v_code
  from public.pager_codes
  where code=trim(coalesce(p_code,'')) and expires_at>now()
    and consumed_at is null and generated_by<>auth.uid()
  order by created_at desc
  limit 1
  for update;

  if not found then
    return jsonb_build_object('correct',false,'message','That code is invalid, expired, already used, or was generated by your own Pager.');
  end if;

  select * into v_puzzle from public.puzzles where id=v_code.puzzle_id and active=true;
  if not found then
    update public.pager_codes set consumed_at=now() where id=v_code.id;
    return jsonb_build_object('correct',false,'message','The Pager challenge is no longer active.');
  end if;

  update public.pager_codes set consumed_at=now() where id=v_code.id;

  if exists(select 1 from public.puzzle_solves where player_id=auth.uid() and puzzle_id=v_puzzle.id) then
    return jsonb_build_object('correct',true,'already_solved',true,'message','You have already completed this Pager challenge.');
  end if;

  insert into public.puzzle_solves(player_id,puzzle_id)
  values(auth.uid(),v_puzzle.id) on conflict do nothing;

  update public.player_progress
  set xp=xp+v_puzzle.reward_xp,
      key_shards=key_shards+v_puzzle.reward_shards,
      updated_at=now()
  where player_id=auth.uid();

  return jsonb_build_object(
    'correct',true,'already_solved',false,
    'xp_awarded',v_puzzle.reward_xp,
    'shards_awarded',v_puzzle.reward_shards,
    'message','Pager code accepted. Challenge completed.'
  );
end;
$$;

revoke all on function public.create_pager_code() from public,anon;
revoke all on function public.redeem_pager_code(text) from public,anon;
grant execute on function public.create_pager_code() to authenticated;
grant execute on function public.redeem_pager_code(text) to authenticated;
